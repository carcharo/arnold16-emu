#!/bin/sh
# Fetch CPCEC (Cesar Nicolas-Gonzalez, GPLv3; github.com/cpcitor/cpcec is the
# mirror) and the Musashi 68000 core (Karl Stenerud, MIT licence) at pinned
# commits, apply the patches in patches/ in order, and build with SDL2.
# Everything lands in work/ (git-ignored): the sources, the ROM files that ship
# with CPCEC, the Arnold 16 boot ROM and the `cpcec` binary. Nothing of CPCEC
# or Musashi is kept in this repo, only our patches.
#
#   sh fetch_build.sh      then   work/cpcec --arnold16 ...
#
# Needs git, a C compiler, Python 3 and SDL2 (macOS: brew install sdl2;
# Ubuntu: apt install libsdl2-dev).
set -e
SHA=c025aab961a796b918cc99bc3e16216ea65bb5d1   # cpcitor/cpcec master, release 20260303
M68K_SHA=313ebf1bd9f4d0d93341eb5ce21fd8a119e9dbdd   # kstenerud/Musashi master, 2026-03-08
cd "$(dirname "$0")"
HERE=$(pwd)
mkdir -p work
cd work
# Musashi: its instruction tables are generated by its own small program
if [ ! -d musashi/.git ]; then
    git clone -q https://github.com/kstenerud/Musashi musashi
fi
cd musashi
git reset -q --hard
if [ "$(git rev-parse HEAD)" != "$M68K_SHA" ]; then
    git fetch -q origin "$M68K_SHA" 2>/dev/null || git fetch -q origin
    git checkout -q "$M68K_SHA"
fi
cc -w -o m68kmake m68kmake.c
./m68kmake >/dev/null
cc -w -O2 -c m68kcpu.c m68kops.c softfloat/softfloat.c
# a disassembler, used only to test our Python 68000 assembler
cc -w -O2 -I. -o ../dis68k "$HERE/tools/dis68k.c" m68kdasm.c
cd ..
if [ ! -d src/.git ]; then
    git clone -q https://github.com/cpcitor/cpcec src
fi
# work/src is about to be wiped. If it holds edits that are not in the patch
# yet, stop rather than lose them.
if [ -f src/cpcec-a16.h ] && [ -z "$FORCE" ]; then
    T=$(mktemp)
    sh "$HERE/tools/mkpatch.sh" "$T"
    if ! cmp -s "$T" "$HERE/patches/0002-arnold16.patch"; then
        rm -f "$T"
        echo "fetch_build.sh: work/src differs from patches/0002-arnold16.patch." >&2
        echo "  To keep your edits: sh tools/mkpatch.sh, then run this again." >&2
        echo "  To discard them (or after pulling a newer patch): make clean, or FORCE=1 sh fetch_build.sh" >&2
        exit 1
    fi
    rm -f "$T"
fi
cd src
# always start from the clean pinned commit, so the result never depends on
# what an earlier run or a hand edit left behind
git reset -q --hard
git clean -q -fd
if [ "$(git rev-parse HEAD)" != "$SHA" ]; then
    git fetch -q origin "$SHA" 2>/dev/null || git fetch -q origin
    git checkout -q "$SHA"
fi
for p in "$HERE"/patches/*.patch; do
    if ! git apply --check "$p" 2>/dev/null; then
        echo "fetch_build.sh: $(basename "$p") does not apply to CPCEC $SHA." >&2
        echo "  If SHA was changed, the patches need rebasing onto the new commit." >&2
        exit 1
    fi
    git apply "$p"
done
# cpcec.c includes <SDL2/SDL.h>, which `sdl2-config --cflags` (it names the
# SDL2 directory itself) doesn't cover on macOS: add the parent directory.
INC=
for d in /opt/homebrew/include /usr/local/include; do
    [ -d "$d/SDL2" ] && INC="$INC -I$d"
done
# shellcheck disable=SC2046
cc -w -DSDL2 -O2 -xc cpcec.c -I../musashi $INC $(sdl2-config --cflags) \
    -xnone ../musashi/m68kcpu.o ../musashi/m68kops.o ../musashi/softfloat.o \
    $(sdl2-config --libs) -lm -o cpcec
# the binary looks for its ROM files in its own directory
cp cpcec ../cpcec
for f in cpc464.rom cpc664.rom cpc6128.rom cpcados.rom cpcplus.rom; do cp "$f" ..; done
cp gpl.txt ../LICENSE.cpcec-gpl3
python3 "$HERE/rom/mkboot.py" ../arnold16.rom
python3 "$HERE/demo/mkdemo.py" ..
echo "cpcec at $(git rev-parse HEAD) with $(ls "$HERE"/patches/*.patch | wc -l | tr -d ' ') patches: $(cd .. && pwd)/cpcec"
